enum QwenOfficialSourcePositiveLog1p {
    private struct Pair {
        let high: Float
        let low: Float
    }

    // dfmul_vf2_vf2_vf
    private static func multiply(_ x: Pair, _ y: Float) -> Pair {
        let high = x.high * y
        let error = (-high).addingProduct(x.high, y)
        return Pair(high: high, low: error.addingProduct(x.low, y))
    }

    // dfadd_vf2_vf_vf
    private static func add(_ x: Float, _ y: Float) -> Pair {
        let high = x + y
        return Pair(high: high, low: (x - high) + y)
    }

    // dfadd_vf2_vf2_vf2
    private static func add(_ x: Pair, _ y: Pair) -> Pair {
        let high = x.high + y.high
        return Pair(high: high, low: (((x.high - high) + y.high) + x.low) + y.low)
    }

    // dfadd_vf2_vf2_vf
    private static func add(_ x: Pair, _ y: Float) -> Pair {
        let high = x.high + y
        return Pair(high: high, low: ((x.high - high) + y) + x.low)
    }

    // dfdiv_vf2_vf2_vf2 with ENABLE_FMA_SP.
    private static func divide(_ numerator: Pair, _ denominator: Pair) -> Pair {
        let reciprocal: Float = 1 / denominator.high
        let high = numerator.high * reciprocal
        let error = (-high).addingProduct(reciprocal, numerator.high)
        let firstCorrection = Float(1).addingProduct(-denominator.high, reciprocal)
        let correction = firstCorrection.addingProduct(-denominator.low, reciprocal)
        let numeratorCorrection = error.addingProduct(numerator.low, reciprocal)
        return Pair(high: high, low: numeratorCorrection.addingProduct(high, correction))
    }

    /// Source core log1p on its nonnegative finite domain. Softplus below its
    /// threshold20 supplies exp(x) <= exp(20), entirely inside this domain.
    static func evaluate(_ value: Float) -> Float {
        precondition(value.isFinite && value >= 0 && value <= Float(1e38))
        if value == 0 { return value }
        let plusOne = value + 1
        let scaled = plusOne * (Float(1) / Float(0.75))
        let exponent = Int32((scaled.bitPattern >> 23) & 255) - 127
        let inversePower = Float(bitPattern: UInt32(bitPattern: Int32(0x3f800000) &- (exponent << 23)))
        let mantissa = (inversePower - 1).addingProduct(value, inversePower)
        var sum = multiply(Pair(high: Float(0.69314718246459960938),
                                low: Float(-1.904654323148236017e-09)), Float(exponent))
        let quotient = divide(Pair(high: mantissa, low: 0), add(Float(2), mantissa))
        let square = quotient.high * quotient.high
        var polynomial = Float(0.3027294874)
        polynomial = Float(0.3996108174).addingProduct(polynomial, square)
        polynomial = Float(0.6666694880).addingProduct(polynomial, square)
        sum = add(sum, Pair(high: quotient.high * 2, low: quotient.low * 2))
        sum = add(sum, (square * quotient.high) * polynomial)
        return sum.high + sum.low
    }
}

