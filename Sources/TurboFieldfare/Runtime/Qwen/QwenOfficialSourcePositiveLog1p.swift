// Pinned CPU positive log1p arithmetic for original-BF16 source softplus.
// SLEEF 3.8.0 commit 5a1d179df9cf652951b59010a2d2075372d67f68,
// xlog1pf and df.h ENABLE_FMA_SP/AArch64 CONFIG=1. No Double arithmetic.
// Copyright Naoki Shibata and contributors 2010 - 2024.
